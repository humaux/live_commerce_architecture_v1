-- Operator registrar creates or rotates the notify token for one SANDBOX payuni connection. The
-- plaintext token (returned by the CLI, never stored) is hashed before this call.
CREATE FUNCTION payments.set_payuni_notify_endpoint(p_tenant uuid,p_store uuid,p_principal uuid,
 p_connection uuid,p_endpoint uuid,p_profile text,p_enabled boolean,p_token_hash bytea)
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path=pg_catalog AS $$
DECLARE acct integration.merchant_accounts%ROWTYPE;
BEGIN
 PERFORM integration.require_stripe_registrar_scope(p_tenant,p_store,p_principal);
 IF p_connection IS NULL OR p_endpoint IS NULL OR p_profile NOT IN ('PROVIDER_MOCK','SANDBOX')
  OR p_enabled IS NULL OR p_token_hash IS NULL OR octet_length(p_token_hash)<>32 THEN
  RAISE EXCEPTION 'invalid PAYUNi notify endpoint input' USING ERRCODE='22023'; END IF;
 SELECT x.* INTO acct FROM integration.merchant_accounts x WHERE x.tenant_id=p_tenant
  AND x.store_id=p_store AND x.id=p_connection AND x.provider='payuni' FOR SHARE;
 IF NOT FOUND OR acct.environment<>'SANDBOX' THEN
  RAISE EXCEPTION 'PAYUNi endpoint account unavailable' USING ERRCODE='PT409'; END IF;
 INSERT INTO payments.payuni_notify_endpoints(endpoint_id,tenant_id,store_id,connection_id,
  environment,account_id,execution_profile,enabled,token_hash)
 VALUES(p_endpoint,p_tenant,p_store,p_connection,acct.environment,acct.account_id,p_profile,
  p_enabled,p_token_hash)
 ON CONFLICT(tenant_id,store_id,connection_id,execution_profile)
  DO UPDATE SET enabled=EXCLUDED.enabled,token_hash=EXCLUDED.token_hash,updated_at=clock_timestamp();
 INSERT INTO ops.audit_events(tenant_id,store_id,principal_id,action)
 VALUES(p_tenant,p_store,p_principal,'payuni.notify_endpoint_set');
END $$;
ALTER FUNCTION payments.set_payuni_notify_endpoint(uuid,uuid,uuid,uuid,uuid,text,boolean,bytea)
 OWNER TO commerce_payment_registry_writer;
REVOKE ALL ON FUNCTION payments.set_payuni_notify_endpoint(uuid,uuid,uuid,uuid,uuid,text,boolean,bytea) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION payments.set_payuni_notify_endpoint(uuid,uuid,uuid,uuid,uuid,text,boolean,bytea)
 TO commerce_payment_registrar;
COMMENT ON FUNCTION payments.set_payuni_notify_endpoint(uuid,uuid,uuid,uuid,uuid,text,boolean,bytea) IS 'payments owner; operator registrar creates or rotates one SANDBOX notify token by connection+profile; no key custody, rebind or LIVE ingress';
