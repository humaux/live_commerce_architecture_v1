/** Resolve existing Chinese locales and keep Japanese unit copy ready for the shared locale owner. */
export function inboxCopy(locale: string): Copy {
  return locale === "en" ? en : locale === "ja" ? ja : tw;
}
/** Map only fixed server vocabulary; never display raw upstream errors or buyer data. */
export function inboxError(locale: string, code: string): string {
  const c = inboxCopy(locale);
  if (code === "forbidden") return c.forbiddenCode;
  if (code === "unauthorized" || code === "signed-out") return c.signedOut;
  return Object.hasOwn(c, code) ? c[code as keyof Copy] : c.unavailable;
}
