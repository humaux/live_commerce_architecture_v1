/** Select only authored copy; no upstream message is rendered. */
export const commentCopy = (locale: string): Copy =>
  locale === "zh-TW" ? tw : locale === "zh-CN" ? cn : en;
/** Map a closed server code, retaining a safe fallback for unknown future states. */
export function commentReason(locale: string, code: string): string {
  const c = commentCopy(locale);
  return Object.hasOwn(c, code) ? c[code as keyof Copy] : c.unavailable;
}
